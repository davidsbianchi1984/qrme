FALLBACK = 0.6      # an unmeasured glyph, assumed wide


def width(s: str, size: float, weight: int = 400) -> float:
    """Width of `s` in px at `size`, in the screens' font stack.

    An unlisted weight falls back to the nearest measured one rather than
    raising: the answer stays approximately right, which is all a layout check
    needs, and a KeyError here would break a build over a font weight.
    """
    row = WIDTHS.get(weight)
    if row is None:
        row = WIDTHS[min(WIDTHS, key=lambda w: abs(w - weight))]
    return sum(row.get(ch, FALLBACK) for ch in s) * size
