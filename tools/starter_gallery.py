def starters() -> list[tuple[str, str, str, list[str]]]:
    """(handle, industry, display name, tags) for every seeded starter.

    Read out of `seed.py` by parsing the literal rather than importing it,
    so generating a page never touches a database or needs the package's
    dependencies installed.
    """
    src = SEED.read_text()
    out: list[tuple[str, str, str, list[str]]] = []
    for name in ("STARTERS", "RATED"):
        m = re.search(rf"^{name}\s*[:=][^=]*=\s*\[", src, re.M)
        if m is None:
            continue
        i = src.index("[", m.end() - 1)
        depth = 0
        for j in range(i, len(src)):
            if src[j] == "[":
                depth += 1
            elif src[j] == "]":
                depth -= 1
                if depth == 0:
                    break
        for row in ast.literal_eval(src[i:j + 1]):
            handle, industry, display, _kind, tags, *_ = row
            out.append((handle, industry, display, list(tags)))
    return out


def cell(handle: str, industry: str, display: str, tags: list[str]) -> str:
    """One card. The caption lives inside the SVG, not under it.

    The old cell put a name, a role and a tag list in `<sub>` beneath a
    portrait, which is a caption pretending to be a profile. The card carries
    all of it — bubble, name, role, industry, stat tiles, Chat — so the only
    thing left out here is the alt text, which has to stay outside the image
    for anybody reading with a screen reader.
    """
    role = ROLES[handle].replace("&amp;", "&")
    return (
        f'    <td align="center" width="50%" valign="top">'
        f'<img src="docs/portraits/cards/{handle}.svg" width="{THUMB}" '
        f'alt="{display} — {role}, {industry.replace("_", " ")}"></td>'
    )


def table() -> str:
    rows = starters()
    missing = [h for h, *_ in rows if h not in ROLES]
    if missing:
        raise SystemExit(
            "starters with no role line in tools/starter_gallery.py: "
            + ", ".join(missing))
    out = ["<table>"]
    for i in range(0, len(rows), COLUMNS):
        out.append("  <tr>")
        out += [cell(*r) for r in rows[i:i + COLUMNS]]
        out.append("  </tr>")
    out.append("</table>")
    return "\n".join(out)


def main() -> int:
    check = "--check" in sys.argv
    text = README.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"README.md is missing {BEGIN} / {END} markers")
    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    new = f"{head}{BEGIN}\n{table()}\n{END}{tail}"
    if new == text:
        print("starter gallery is up to date")
        return 0
    if check:
        print("starter gallery is stale — run tools/starter_gallery.py")
        return 1
    README.write_text(new)
    print(f"rewrote the starter gallery: {len(starters())} profiles, "
          f"{COLUMNS} columns")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


