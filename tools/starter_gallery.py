"""Regenerate the starter-collection gallery in README.md.

The gallery used to be 34 hand-written `<td>` blocks. Two things went wrong
with that, and both are the reason this file exists.

**It drifted from the seed list.** The starters live in `qrme/seed.py`; the
gallery was a second copy of their names maintained by hand, so a starter could
be added, renamed, or regrounded without the page showing it.

**It was five columns wide.** Five 118px portraits is roughly 590px of content,
and a phone gives about 390. On GitHub's mobile view the fourth column was
sliced mid-word and the fifth was gone entirely — every profile past the third
was unreachable to anybody reading on a phone, which is most people. Three
columns fit. That is the whole reason for the number.

**And it showed a name and an industry.** A profile's own front page (screen 5)
carries an avatar bubble, a role, stat tiles and a Chat button. The gallery
showed a portrait with two lines of caption under it, so the starters looked
thinner on the page than they are in the product. Each cell is now the card
itself, generated by `tools/starter_cards.py` — run that first, this second.

Roles are curated here rather than extracted from the bios. A regex over "A
warm, plain-spoken physician and health educator with twenty years…" produces
something almost right, and almost right in 34 places is worse than a list
somebody read once. Each line below is the credential its bio opens with,
shortened. `check()` fails if a starter has no role, so adding one to
`seed.py` without a line here is a build error rather than a blank cell.

    python3 tools/starter_gallery.py           # rewrite README.md in place
    python3 tools/starter_gallery.py --check   # verify, exit 1 on drift
"""

